const I18n = {
  currentLang: 'en',

  init() {
    const saved = localStorage.getItem('smart_poultry_lang') || 'en';
    this.setLanguage(saved);
  },

  get(key, fallback = '') {
    const langDict = TRANSLATIONS[this.currentLang] || TRANSLATIONS['en'];
    return langDict[key] || TRANSLATIONS['en'][key] || fallback || key;
  },

  setLanguage(lang) {
    if (!TRANSLATIONS[lang]) lang = 'en';
    this.currentLang = lang;
    localStorage.setItem('smart_poultry_lang', lang);

    // Update all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.get(key);
      if (text) {
        el.textContent = text;
      }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const text = this.get(key);
      if (text) {
        el.setAttribute('placeholder', text);
      }
    });

    // Update active flag / language button text
    const langLabel = document.getElementById('currentLangLabel');
    if (langLabel) {
      const map = { en: 'EN', hi: 'हिन्दी', te: 'తెలుగు', ta: 'தமிழ்', bn: 'বাংলা', es: 'ES' };
      langLabel.textContent = map[lang] || lang.toUpperCase();
    }

    // Dispatch event in case dynamic parts need re-rendering
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }
};
